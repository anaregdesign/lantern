export function operationalFieldGuidance(
  group: OperationalGroup,
  key: string,
  wholeNumber: boolean,
) {
  const [meaning, initial, range, example, min = "0", max = i64] =
    guidance[group][key]!;
  return {
    min,
    max: wholeNumber ? max : undefined,
    help: {
      meaning,
      example,
      details: `${wholeNumber ? `Whole number from ${min} to ${max}. ` : ""}${range} Fresh startup default: ${initial}. Empty is invalid; it does not select a default. Effective values can come from environment or managed policy.`,
    },
  };
}
